let currentStory = null;
let readerFontSize = 20;
let toastTimer;

function safeReadSaved() {
  try { return new Set(JSON.parse(localStorage.getItem("etarismo-saved") || "[]")); }
  catch { return new Set(); }
}

function persistSaved() {
  try { localStorage.setItem("etarismo-saved", JSON.stringify([...saved])); } catch { /* storage may be disabled */ }
  updateSavedCount();
}

function showToast(message) {
  toast.textContent = message;
  toast.classList.add("visible");
  clearTimeout(toastTimer);
  toastTimer = setTimeout(() => toast.classList.remove("visible"), 2400);
}

function createCard(story) {
  const article = document.createElement("article");
  article.className = "story-card";
  article.dataset.category = story.category;
  article.dataset.id = story.id;
  const background = story.category === "Economia" ? "#64715c" : story.category === "Sociedade" ? "#566d68" : story.category === "Direitos" ? "#415343" : "#49583f";
  article.innerHTML = `
    <div class="story-art" style="--art-bg:${background}">
      <span class="story-tag">${story.category.toUpperCase()}</span>
      <button class="save-story" type="button" data-save="${story.id}" aria-label="Salvar: ${story.title}" aria-pressed="${saved.has(story.id)}">${saved.has(story.id) ? "◆" : "♧"}</button>
      <span class="story-number">${story.id}</span><span class="story-art-label">${story.art}</span>
    </div>
    <div class="story-meta"><span>${story.tag}</span><span>2 MIN DE LEITURA</span></div>
    <h3 class="story-title"><a href="#materias" data-open-article="${story.id}">${story.title}</a><span aria-hidden="true">↗</span></h3>
    <p class="story-deck">${story.deck}</p>`;
  return article;
}

function renderStories() {
  const matching = stories.filter(story => {
    const matchesCategory = activeFilter === "Todas" || story.category === activeFilter;
    const text = `${story.title} ${story.category} ${story.tag} ${story.deck}`.toLocaleLowerCase("pt-BR");
    const matchesQuery = !activeQuery || text.includes(activeQuery.toLocaleLowerCase("pt-BR"));
    const matchesSaved = !document.body.classList.contains("show-saved") || saved.has(story.id);
    return matchesCategory && matchesQuery && matchesSaved;
  });
  const totalPages = Math.max(1, Math.ceil(matching.length / 3));
  carouselPage = Math.min(carouselPage, totalPages);
  const filteredView = activeQuery || document.body.classList.contains("show-saved");
  const visible = allStories || filteredView ? matching : matching.slice((carouselPage - 1) * 3, carouselPage * 3);
  grid.replaceChildren(...visible.map(createCard));
  document.querySelector("#result-count").textContent = matching.length ? `${matching.length} ${matching.length === 1 ? "matéria" : "matérias"}` : "Nenhuma matéria encontrada nesta seleção.";
  document.querySelector("#show-all").textContent = allStories ? "Mostrar destaques ↗" : "Mostrar todas as matérias ↗";
  document.querySelector("#show-all").setAttribute("aria-pressed", String(allStories));
  carouselStatus.dataset.page = String(carouselPage);
  carouselStatus.innerHTML = `${String(carouselPage).padStart(2, "0")} <span></span> ${String(totalPages).padStart(2, "0")}`;
  const carouselHidden = allStories || filteredView || totalPages <= 1;
  carouselStatus.hidden = carouselHidden;
  document.querySelector(".carousel-buttons").hidden = carouselHidden;
  document.querySelector("#previous-stories").disabled = carouselPage === 1;
  document.querySelector("#next-stories").disabled = carouselPage === totalPages;
  updateSavedCount();
}

function updateSavedCount() {
  const badge = document.querySelector("#saved-count");
  badge.textContent = saved.size ? String(saved.size) : "";
  badge.classList.toggle("has-count", saved.size > 0);
  document.querySelector("#saved-toggle").setAttribute("aria-pressed", String(document.body.classList.contains("show-saved")));
}

function getStory(id) { return id === "editorial" ? editorial : stories.find(item => item.id === id); }
const readingOrder = [editorial, ...stories];

function createPopulationChart() {
  const figure = document.createElement("figure");
  figure.className = "article-chart";
  const caption = document.createElement("figcaption");
  caption.textContent = "Pessoas com 60 anos ou mais na população brasileira";
  figure.append(caption);
  const plot = document.createElement("div");
  plot.className = "article-chart-plot";
  plot.setAttribute("role", "img");
  plot.setAttribute("aria-label", "Participação da população com 60 anos ou mais: 8,7% em 2000, 15,6% em 2023 e projeção de 37,8% em 2070.");
  [["2000", 8.7], ["2023", 15.6], ["2070 (projeção)", 37.8]].forEach(([year, value]) => {
    const column = document.createElement("div");
    column.className = "article-chart-column";
    const label = document.createElement("strong");
    label.textContent = `${String(value).replace(".", ",")}%`;
    const bar = document.createElement("span");
    bar.className = "article-chart-bar";
    bar.style.height = `${(value / 40) * 100}%`;
    const yearLabel = document.createElement("small");
    yearLabel.textContent = year;
    column.append(label, bar, yearLabel);
    plot.append(column);
  });
  figure.append(plot);
  const source = document.createElement("p");
  source.className = "article-chart-source";
  source.textContent = "IBGE · PROJEÇÕES DA POPULAÇÃO, REVISÃO 2024";
  figure.append(source);
  return figure;
}

function openStory(id) {
  const story = getStory(id);
  if (!story) return;
  currentStory = story;
  document.querySelector("#reader-title").textContent = story.title;
  document.querySelector("#reader-category").textContent = story.tag || story.category;
  document.querySelector("#reader-index").textContent = `PÁGINA ${story.id} / 20`;
  const readingIndex = readingOrder.findIndex(item => item.id === story.id);
  const previousStory = readingOrder[readingIndex - 1];
  const nextStory = readingOrder[readingIndex + 1];
  const previousButton = document.querySelector("#previous-article");
  const nextButton = document.querySelector("#next-article");
  previousButton.disabled = !previousStory;
  nextButton.disabled = !nextStory;
  document.querySelector("#previous-article-title").textContent = previousStory?.title || "";
  document.querySelector("#next-article-title").textContent = nextStory?.title || "";
  previousButton.setAttribute("aria-label", previousStory ? `Matéria anterior: ${previousStory.title}` : "Não há matéria anterior");
  nextButton.setAttribute("aria-label", nextStory ? `Próxima matéria: ${nextStory.title}` : "Não há próxima matéria");
  const body = document.querySelector("#reader-body");
  body.replaceChildren();
  if (story.body?.length) {
    story.body.forEach((paragraph, index) => {
      const p = document.createElement("p");
      p.textContent = paragraph;
      if (index === story.body.length - 1 && /Fonte:|Pierre Bourdieu\./.test(paragraph)) p.className = "citation";
      body.append(p);
      if (story.id === "05" && index === 0) body.append(createPopulationChart());
    });
    if (story.dataNotes?.length) {
      const section = document.createElement("section");
      section.className = "reader-data-notes";
      const heading = document.createElement("h3");
      heading.textContent = "A Realidade em Números";
      section.append(heading);
      story.dataNotes.forEach((note, index) => {
        const p = document.createElement("p");
        p.textContent = note;
        if (index === story.dataNotes.length - 1) p.className = "citation";
        section.append(p);
      });
      body.append(section);
    }
  } else {
    const summary = document.createElement("div");
    summary.className = "reader-summary";
    summary.innerHTML = `<strong>NA EDIÇÃO</strong>`;
    const text = document.createElement("span");
    text.textContent = story.deck;
    summary.append(text);
    body.append(summary);
  }
  reader.classList.remove("reader-dark");
  readerFontSize = 20;
  body.style.fontSize = `${readerFontSize}px`;
  document.querySelector("#reader-save").textContent = saved.has(story.id) ? "◆" : "♧";
  document.querySelector("#reader-save").setAttribute("aria-pressed", String(saved.has(story.id)));
  reader.showModal();
  document.querySelector(".reader-content").scrollTop = 0;
}

grid.addEventListener("click", event => {
  const saveButton = event.target.closest("[data-save]");
  if (saveButton) {
    const id = saveButton.dataset.save;
    if (saved.has(id)) saved.delete(id); else saved.add(id);
    persistSaved();
    renderStories();
    showToast(saved.has(id) ? "Matéria salva para depois." : "Matéria removida dos salvos.");
    return;
  }
  const link = event.target.closest("[data-open-article]");
  if (link) { event.preventDefault(); openStory(link.dataset.openArticle); }
});

