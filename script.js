const carouselStatus = document.querySelector("#carousel-status");
function changeCarousel(direction) {
  if (activeQuery || document.body.classList.contains("show-saved")) return;
  const pageCount = Math.max(1, Math.ceil(stories.filter(story => activeFilter === "Todas" || story.category === activeFilter).length / 3));
  if (pageCount <= 1) return;
  allStories = false;
  carouselPage = Math.max(1, Math.min(pageCount, carouselPage + direction));
  renderStories();
}
document.querySelector("#next-stories").addEventListener("click", () => changeCarousel(1));
document.querySelector("#previous-stories").addEventListener("click", () => changeCarousel(-1));

renderStories();
