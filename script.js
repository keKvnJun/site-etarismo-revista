document.querySelector("#share-article").addEventListener("click", async () => {
  if (!currentStory) return;
  const shareData = { title: currentStory.title, text: currentStory.deck, url: location.href.split("#")[0] + `#materia-${currentStory.id}` };
  try {
    if (navigator.share) await navigator.share(shareData);
    else if (navigator.clipboard) { await navigator.clipboard.writeText(`${shareData.title}\n${shareData.url}`); showToast("Link da matéria copiado."); }
    else showToast("Use a barra de endereço para compartilhar esta edição.");
  } catch (error) { if (error.name !== "AbortError") showToast("Não foi possível compartilhar agora."); }
});
document.querySelector("#next-article").addEventListener("click", () => {
  if (!currentStory) return;
  const idx = readingOrder.findIndex(story => story.id === currentStory.id);
  const next = readingOrder[idx + 1];
  if (next) openStory(next.id);
});
document.querySelector("#previous-article").addEventListener("click", () => {
  if (!currentStory) return;
  const idx = readingOrder.findIndex(story => story.id === currentStory.id);
  const previous = readingOrder[idx - 1];
  if (previous) openStory(previous.id);
});
